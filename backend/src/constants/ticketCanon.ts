  [TICKET_STATUS.IN_PROGRESS]: [TICKET_STATUS.ON_HOLD, TICKET_STATUS.RESOLVED],
  [TICKET_STATUS.ON_HOLD]: [TICKET_STATUS.IN_PROGRESS, TICKET_STATUS.RESOLVED],
