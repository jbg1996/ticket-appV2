export const TICKET_STATUS = {
  NEW: 'NEW',
  IN_PROGRESS: 'IN_PROGRESS',
  ON_HOLD: 'ON_HOLD',
  RESOLVED: 'RESOLVED',
  CLOSED: 'CLOSED'
} as const;

export const TICKET_PRIORITY = {
  LOW: 'LOW',
  MEDIUM: 'MEDIUM',
  HIGH: 'HIGH',
  CRITICAL: 'CRITICAL'
} as const;

export const TICKET_TYPE = {
  REQUEST: 'REQUEST',
  INCIDENT: 'INCIDENT',
  ACCESS: 'ACCESS',
  HARDWARE: 'HARDWARE',
  SOFTWARE: 'SOFTWARE',
  OTHER: 'OTHER'
} as const;

export type TicketStatusName = (typeof TICKET_STATUS)[keyof typeof TICKET_STATUS];

